-- 1. Enum types (guarded so they won't conflict if defined elsewhere)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'bicycle_type' AND n.nspname = 'bicycle_rental'
    ) THEN
        CREATE TYPE bicycle_rental.bicycle_type AS ENUM ('regular', 'electric');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'audit_action_type' AND n.nspname = 'bicycle_rental'
    ) THEN
        CREATE TYPE bicycle_rental.audit_action_type AS ENUM (
            'rider_block',
            'rider_unblock',
            'station_create',
            'station_update',
            'maintenance_handover',
            'maintenance_return',
            'maintenance_state_update',
            'staff_return'
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'audit_record_type' AND n.nspname = 'bicycle_rental'
    ) THEN
        CREATE TYPE bicycle_rental.audit_record_type AS ENUM (
            'Rider',
            'Bicycle',
            'Station',
            'Rental'
        );
    END IF;
END $$;

-- 2. Tariff table & constraints (F-078, F-079, F-085)
CREATE TABLE bicycle_rental.tariff (
    tariff_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bicycle_type         bicycle_rental.bicycle_type NOT NULL,
    price_per_block      NUMERIC(12, 2) NOT NULL,
    block_length_seconds INTEGER NOT NULL,
    currency             VARCHAR(10) NOT NULL,
    is_active            BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_tariff_id_bicycle_type UNIQUE (tariff_id, bicycle_type),
    CONSTRAINT chk_tariff_values CHECK (
        price_per_block >= 0
        AND block_length_seconds > 0
        AND TRIM(currency) <> ''
    )
);

-- At most one active tariff per bicycle_type
CREATE UNIQUE INDEX uq_tariff_one_active_per_type
    ON bicycle_rental.tariff (bicycle_type)
    WHERE is_active = TRUE;

-- Prohibit operational INSERT/UPDATE/DELETE unless privileged setup mode is active
CREATE OR REPLACE FUNCTION bicycle_rental.enforce_tariff_privileged_only()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF current_setting('bicycle_rental.privileged_setup', TRUE) IS DISTINCT FROM 'true' THEN
        RAISE EXCEPTION 'Tariff records cannot be inserted, updated, or deleted operationally.';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_tariff_privileged_only
    BEFORE INSERT OR UPDATE OR DELETE ON bicycle_rental.tariff
    FOR EACH ROW
    EXECUTE FUNCTION bicycle_rental.enforce_tariff_privileged_only();

-- Ensure active 'regular' and 'electric' tariffs both exist and share the same currency
CREATE OR REPLACE FUNCTION bicycle_rental.validate_active_tariffs()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_regular_currency  VARCHAR(10);
    v_electric_currency VARCHAR(10);
BEGIN
    SELECT currency INTO v_regular_currency
    FROM bicycle_rental.tariff
    WHERE bicycle_type = 'regular' AND is_active = TRUE;

    SELECT currency INTO v_electric_currency
    FROM bicycle_rental.tariff
    WHERE bicycle_type = 'electric' AND is_active = TRUE;

    IF v_regular_currency IS NULL OR v_electric_currency IS NULL THEN
        RAISE EXCEPTION 'Both active regular and active electric tariffs must exist.';
    END IF;

    IF v_regular_currency <> v_electric_currency THEN
        RAISE EXCEPTION 'Active regular (%) and electric (%) tariffs must share the same currency.',
            v_regular_currency, v_electric_currency;
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_tariff_active_pair_and_currency
    AFTER INSERT OR UPDATE ON bicycle_rental.tariff
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION bicycle_rental.validate_active_tariffs();

-- 3. AuditEntry and AuditDetail tables (F-098 through F-106)
CREATE TABLE bicycle_rental.audit_entry (
    audit_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id            BIGINT NOT NULL,
    action_type         bicycle_rental.audit_action_type NOT NULL,
    primary_record_type bicycle_rental.audit_record_type NOT NULL,
    primary_record_id   BIGINT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Attach FK to staff(account_id) automatically if staff table already exists
DO $$
BEGIN
    IF to_regclass('bicycle_rental.staff') IS NOT NULL THEN
        ALTER TABLE bicycle_rental.audit_entry
            ADD CONSTRAINT fk_audit_entry_staff
            FOREIGN KEY (staff_id) REFERENCES bicycle_rental.staff (account_id);
    END IF;
END $$;

CREATE INDEX idx_audit_entry_created_at
    ON bicycle_rental.audit_entry (created_at DESC);

CREATE INDEX idx_audit_entry_staff_created_at
    ON bicycle_rental.audit_entry (staff_id, created_at DESC);

CREATE INDEX idx_audit_entry_action_created_at
    ON bicycle_rental.audit_entry (action_type, created_at DESC);

CREATE INDEX idx_audit_entry_primary_record
    ON bicycle_rental.audit_entry (primary_record_type, primary_record_id, created_at DESC);

CREATE TABLE bicycle_rental.audit_detail (
    audit_id            BIGINT NOT NULL REFERENCES bicycle_rental.audit_entry (audit_id),
    detail_no           INTEGER NOT NULL,
    subject_record_type bicycle_rental.audit_record_type NOT NULL,
    subject_record_id   BIGINT NOT NULL,
    field_name          VARCHAR(100) NOT NULL,
    previous_value      JSONB,
    new_value           JSONB,

    PRIMARY KEY (audit_id, detail_no),
    CONSTRAINT chk_audit_detail_no_positive CHECK (detail_no > 0),
    CONSTRAINT chk_audit_detail_field_nonblank CHECK (TRIM(field_name) <> ''),
    CONSTRAINT chk_audit_detail_no_secrets CHECK (
        LOWER(TRIM(field_name)) NOT IN (
            'password', 'password_hash', 'token', 'session_token', 'secret'
        )
    )
);

-- Enforce append-only on AuditEntry and AuditDetail (F-103)
CREATE OR REPLACE FUNCTION bicycle_rental.enforce_audit_append_only()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF current_setting('bicycle_rental.privileged_reset', TRUE) IS DISTINCT FROM 'true' THEN
        RAISE EXCEPTION 'Audit tables are append-only: % on % is prohibited.', TG_OP, TG_TABLE_NAME;
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_audit_entry_append_only
    BEFORE UPDATE OR DELETE ON bicycle_rental.audit_entry
    FOR EACH ROW
    EXECUTE FUNCTION bicycle_rental.enforce_audit_append_only();

CREATE TRIGGER trg_audit_detail_append_only
    BEFORE UPDATE OR DELETE ON bicycle_rental.audit_detail
    FOR EACH ROW
    EXECUTE FUNCTION bicycle_rental.enforce_audit_append_only();

-- Enforce at least one AuditDetail row per AuditEntry (F-106)
CREATE OR REPLACE FUNCTION bicycle_rental.verify_audit_entry_has_details()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM bicycle_rental.audit_detail WHERE audit_id = NEW.audit_id
    ) THEN
        RAISE EXCEPTION 'AuditEntry % must have at least one AuditDetail row.', NEW.audit_id;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_audit_entry_require_details
    AFTER INSERT ON bicycle_rental.audit_entry
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION bicycle_rental.verify_audit_entry_has_details();

-- Validate logical record references whenever target tables exist
CREATE OR REPLACE FUNCTION bicycle_rental.validate_audit_record_reference(
    p_record_type bicycle_rental.audit_record_type,
    p_record_id   BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_exists BOOLEAN;
BEGIN
    IF p_record_type = 'Rider' AND to_regclass('bicycle_rental.rider') IS NOT NULL THEN
        SELECT EXISTS (SELECT 1 FROM bicycle_rental.rider WHERE account_id = p_record_id) INTO v_exists;
        IF NOT v_exists THEN
            RAISE EXCEPTION 'Referenced Rider (%) does not exist.', p_record_id;
        END IF;
    ELSIF p_record_type = 'Bicycle' AND to_regclass('bicycle_rental.bicycle') IS NOT NULL THEN
        SELECT EXISTS (SELECT 1 FROM bicycle_rental.bicycle WHERE bicycle_id = p_record_id) INTO v_exists;
        IF NOT v_exists THEN
            RAISE EXCEPTION 'Referenced Bicycle (%) does not exist.', p_record_id;
        END IF;
    ELSIF p_record_type = 'Station' AND to_regclass('bicycle_rental.station') IS NOT NULL THEN
        SELECT EXISTS (SELECT 1 FROM bicycle_rental.station WHERE station_id = p_record_id) INTO v_exists;
        IF NOT v_exists THEN
            RAISE EXCEPTION 'Referenced Station (%) does not exist.', p_record_id;
        END IF;
    ELSIF p_record_type = 'Rental' AND to_regclass('bicycle_rental.rental') IS NOT NULL THEN
        SELECT EXISTS (SELECT 1 FROM bicycle_rental.rental WHERE rental_id = p_record_id) INTO v_exists;
        IF NOT v_exists THEN
            RAISE EXCEPTION 'Referenced Rental (%) does not exist.', p_record_id;
        END IF;
    END IF;
END;
$$;

-- 4. Reusable audit-writing function (participates in caller's transaction - F-104)
CREATE OR REPLACE FUNCTION bicycle_rental.record_audit_event(
    p_staff_id            BIGINT,
    p_action_type         bicycle_rental.audit_action_type,
    p_primary_record_type bicycle_rental.audit_record_type,
    p_primary_record_id   BIGINT,
    p_details             JSONB
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_audit_id   BIGINT;
    v_detail     JSONB;
    v_idx        INTEGER;
    v_subj_type  bicycle_rental.audit_record_type;
    v_subj_id    BIGINT;
    v_field_name VARCHAR(100);
    v_prev_val   JSONB;
    v_new_val    JSONB;
BEGIN
    IF p_staff_id IS NULL THEN
        RAISE EXCEPTION 'staff_id is required for audit entries.';
    END IF;

    IF p_details IS NULL OR jsonb_typeof(p_details) <> 'array' OR jsonb_array_length(p_details) < 1 THEN
        RAISE EXCEPTION 'p_details must be a non-empty JSONB array of detail objects.';
    END IF;

    PERFORM bicycle_rental.validate_audit_record_reference(p_primary_record_type, p_primary_record_id);

    INSERT INTO bicycle_rental.audit_entry (
        staff_id,
        action_type,
        primary_record_type,
        primary_record_id,
        created_at
    )
    VALUES (
        p_staff_id,
        p_action_type,
        p_primary_record_type,
        p_primary_record_id,
        CURRENT_TIMESTAMP
    )
    RETURNING audit_id INTO v_audit_id;

    FOR v_detail, v_idx IN
        SELECT elem, ord::INTEGER
        FROM jsonb_array_elements(p_details) WITH ORDINALITY AS t(elem, ord)
    LOOP
        IF jsonb_typeof(v_detail) <> 'object' THEN
            RAISE EXCEPTION 'Audit detail element % must be a JSON object.', v_idx;
        END IF;

        v_subj_type  := (v_detail ->> 'subject_record_type')::bicycle_rental.audit_record_type;
        v_subj_id    := (v_detail ->> 'subject_record_id')::BIGINT;
        v_field_name := v_detail ->> 'field_name';
        v_prev_val   := v_detail -> 'previous_value';
        v_new_val    := v_detail -> 'new_value';

        IF v_subj_type IS NULL OR v_subj_id IS NULL OR v_field_name IS NULL OR TRIM(v_field_name) = '' THEN
            RAISE EXCEPTION 'Audit detail % is missing subject_record_type, subject_record_id, or field_name.', v_idx;
        END IF;

        IF v_prev_val = 'null'::JSONB THEN
            v_prev_val := NULL;
        END IF;
        IF v_new_val = 'null'::JSONB THEN
            v_new_val := NULL;
        END IF;

        PERFORM bicycle_rental.validate_audit_record_reference(v_subj_type, v_subj_id);

        INSERT INTO bicycle_rental.audit_detail (
            audit_id,
            detail_no,
            subject_record_type,
            subject_record_id,
            field_name,
            previous_value,
            new_value
        )
        VALUES (
            v_audit_id,
            v_idx,
            v_subj_type,
            v_subj_id,
            v_field_name,
            v_prev_val,
            v_new_val
        );
    END LOOP;

    RETURN v_audit_id;
END;
$$;